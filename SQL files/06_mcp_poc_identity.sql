-- 06_mcp_poc_identity.sql
-- Identity + data-protection layer for the Foundry -> SPCS MCP PoC.
-- Two personas call the same MCP endpoint with their own PAT:
--   MCP_POC_CEO      -> PARK_CEO      : sees everything
--   MCP_POC_ANALYST  -> PARK_ANALYST  : one park only, no FINANCE schema, PII/pay masked
-- Snowflake (not the MCP server) enforces the difference.

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE COMPUTE_WH;

-- ---------------------------------------------------------------- roles
CREATE ROLE IF NOT EXISTS PARK_CEO          COMMENT = 'MCP PoC persona: executive, full access';
CREATE ROLE IF NOT EXISTS PARK_ANALYST      COMMENT = 'MCP PoC persona: entry-level analyst, restricted';
CREATE ROLE IF NOT EXISTS MCP_SERVICE_OWNER COMMENT = 'Owns the SPCS MCP service; holds caller grants';
GRANT ROLE PARK_CEO          TO ROLE SYSADMIN;
GRANT ROLE PARK_ANALYST      TO ROLE SYSADMIN;
GRANT ROLE MCP_SERVICE_OWNER TO ROLE SYSADMIN;

-- ---------------------------------------------------------------- common grants
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_AGENT_USER TO ROLE PARK_CEO;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_AGENT_USER TO ROLE PARK_ANALYST;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE PARK_CEO;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE PARK_ANALYST;
GRANT USAGE ON DATABASE AMUSEMENT_PARK_DB TO ROLE PARK_CEO;
GRANT USAGE ON DATABASE AMUSEMENT_PARK_DB TO ROLE PARK_ANALYST;
GRANT USAGE ON AGENT AMUSEMENT_PARK_DB.ANALYTICS.AMUSEMENT_PARK_INSIGHTS_AGENT TO ROLE PARK_CEO;
GRANT USAGE ON AGENT AMUSEMENT_PARK_DB.ANALYTICS.AMUSEMENT_PARK_INSIGHTS_AGENT TO ROLE PARK_ANALYST;

-- CEO: every schema, table, view, semantic view
GRANT USAGE ON ALL SCHEMAS IN DATABASE AMUSEMENT_PARK_DB TO ROLE PARK_CEO;
GRANT SELECT ON ALL TABLES IN DATABASE AMUSEMENT_PARK_DB TO ROLE PARK_CEO;
GRANT SELECT ON ALL VIEWS  IN DATABASE AMUSEMENT_PARK_DB TO ROLE PARK_CEO;
GRANT SELECT ON ALL SEMANTIC VIEWS IN SCHEMA AMUSEMENT_PARK_DB.ANALYTICS TO ROLE PARK_CEO;

-- Analyst: CORE + OPS + ANALYTICS, but NOT the FINANCE schema / financials semantic view
GRANT USAGE ON SCHEMA AMUSEMENT_PARK_DB.CORE      TO ROLE PARK_ANALYST;
GRANT USAGE ON SCHEMA AMUSEMENT_PARK_DB.OPS       TO ROLE PARK_ANALYST;
GRANT USAGE ON SCHEMA AMUSEMENT_PARK_DB.ANALYTICS TO ROLE PARK_ANALYST;
GRANT SELECT ON ALL TABLES IN SCHEMA AMUSEMENT_PARK_DB.CORE TO ROLE PARK_ANALYST;
GRANT SELECT ON ALL TABLES IN SCHEMA AMUSEMENT_PARK_DB.OPS  TO ROLE PARK_ANALYST;
GRANT SELECT ON VIEW AMUSEMENT_PARK_DB.ANALYTICS.V_RIDE_PERFORMANCE       TO ROLE PARK_ANALYST;
GRANT SELECT ON VIEW AMUSEMENT_PARK_DB.ANALYTICS.V_DAILY_PARK_PERFORMANCE TO ROLE PARK_ANALYST;
GRANT SELECT ON SEMANTIC VIEW AMUSEMENT_PARK_DB.ANALYTICS.RIDE_OPERATIONS_SV TO ROLE PARK_ANALYST;
GRANT SELECT ON SEMANTIC VIEW AMUSEMENT_PARK_DB.ANALYTICS.OUTLET_SALES_SV    TO ROLE PARK_ANALYST;

-- ---------------------------------------------------------------- policies
CREATE SCHEMA IF NOT EXISTS AMUSEMENT_PARK_DB.GOVERNANCE;

-- Row access: PARK_ANALYST only sees park 1 (Mountain Peaks Adventure Park).
-- Everyone else (CEO, admins, existing users) is unaffected.
CREATE OR REPLACE ROW ACCESS POLICY AMUSEMENT_PARK_DB.GOVERNANCE.RAP_PARK_SCOPE
  AS (park_id NUMBER) RETURNS BOOLEAN ->
  CASE WHEN CURRENT_ROLE() = 'PARK_ANALYST' THEN park_id = 1 ELSE TRUE END;

-- Masking: analyst cannot see guest/employee names or pay/labour cost.
CREATE OR REPLACE MASKING POLICY AMUSEMENT_PARK_DB.GOVERNANCE.MP_MASK_TEXT
  AS (val STRING) RETURNS STRING ->
  CASE WHEN CURRENT_ROLE() = 'PARK_ANALYST' THEN '***MASKED***' ELSE val END;
CREATE OR REPLACE MASKING POLICY AMUSEMENT_PARK_DB.GOVERNANCE.MP_MASK_NUMBER
  AS (val NUMBER(38,2)) RETURNS NUMBER(38,2) ->
  CASE WHEN CURRENT_ROLE() = 'PARK_ANALYST' THEN NULL ELSE val END;

-- ---------------------------------------------------------------- attach policies
ALTER TABLE AMUSEMENT_PARK_DB.OPS.FACT_RIDE_OPERATION ADD ROW ACCESS POLICY AMUSEMENT_PARK_DB.GOVERNANCE.RAP_PARK_SCOPE ON (PARK_ID);
ALTER TABLE AMUSEMENT_PARK_DB.OPS.FACT_OUTLET_SALE    ADD ROW ACCESS POLICY AMUSEMENT_PARK_DB.GOVERNANCE.RAP_PARK_SCOPE ON (PARK_ID);
ALTER TABLE AMUSEMENT_PARK_DB.OPS.FACT_PARK_VISIT     ADD ROW ACCESS POLICY AMUSEMENT_PARK_DB.GOVERNANCE.RAP_PARK_SCOPE ON (PARK_ID);
ALTER TABLE AMUSEMENT_PARK_DB.OPS.FACT_TICKET_SALE    ADD ROW ACCESS POLICY AMUSEMENT_PARK_DB.GOVERNANCE.RAP_PARK_SCOPE ON (PARK_ID);
ALTER TABLE AMUSEMENT_PARK_DB.OPS.FACT_LABOR_SHIFT    ADD ROW ACCESS POLICY AMUSEMENT_PARK_DB.GOVERNANCE.RAP_PARK_SCOPE ON (PARK_ID);
ALTER TABLE AMUSEMENT_PARK_DB.OPS.FACT_MAINTENANCE_WORK_ORDER ADD ROW ACCESS POLICY AMUSEMENT_PARK_DB.GOVERNANCE.RAP_PARK_SCOPE ON (PARK_ID);

ALTER TABLE AMUSEMENT_PARK_DB.CORE.DIM_GUEST    MODIFY COLUMN FIRST_NAME SET MASKING POLICY AMUSEMENT_PARK_DB.GOVERNANCE.MP_MASK_TEXT;
ALTER TABLE AMUSEMENT_PARK_DB.CORE.DIM_GUEST    MODIFY COLUMN LAST_NAME  SET MASKING POLICY AMUSEMENT_PARK_DB.GOVERNANCE.MP_MASK_TEXT;
ALTER TABLE AMUSEMENT_PARK_DB.CORE.DIM_EMPLOYEE MODIFY COLUMN FIRST_NAME SET MASKING POLICY AMUSEMENT_PARK_DB.GOVERNANCE.MP_MASK_TEXT;
ALTER TABLE AMUSEMENT_PARK_DB.CORE.DIM_EMPLOYEE MODIFY COLUMN LAST_NAME  SET MASKING POLICY AMUSEMENT_PARK_DB.GOVERNANCE.MP_MASK_TEXT;
ALTER TABLE AMUSEMENT_PARK_DB.CORE.DIM_EMPLOYEE MODIFY COLUMN HOURLY_RATE SET MASKING POLICY AMUSEMENT_PARK_DB.GOVERNANCE.MP_MASK_NUMBER;
ALTER TABLE AMUSEMENT_PARK_DB.OPS.FACT_LABOR_SHIFT MODIFY COLUMN LABOR_COST_AMOUNT SET MASKING POLICY AMUSEMENT_PARK_DB.GOVERNANCE.MP_MASK_NUMBER;

-- ---------------------------------------------------------------- persona users
-- Cortex Agents authorise with the user's DEFAULT role, so set it explicitly.
CREATE USER IF NOT EXISTS MCP_POC_CEO
  TYPE = SERVICE DEFAULT_ROLE = PARK_CEO DEFAULT_WAREHOUSE = COMPUTE_WH
  COMMENT = 'MCP PoC persona: CEO';
CREATE USER IF NOT EXISTS MCP_POC_ANALYST
  TYPE = SERVICE DEFAULT_ROLE = PARK_ANALYST DEFAULT_WAREHOUSE = COMPUTE_WH
  COMMENT = 'MCP PoC persona: entry-level analyst';
GRANT ROLE PARK_CEO     TO USER MCP_POC_CEO;
GRANT ROLE PARK_ANALYST TO USER MCP_POC_ANALYST;

-- PATs normally require a network policy. For the PoC we relax that with an
-- authentication policy scoped to these two users only.
-- PRODUCTION: replace with a network policy limited to Azure Foundry egress IPs.
CREATE AUTHENTICATION POLICY IF NOT EXISTS AMUSEMENT_PARK_DB.GOVERNANCE.MCP_POC_PAT_POLICY
  AUTHENTICATION_METHODS = ('PROGRAMMATIC_ACCESS_TOKEN', 'KEYPAIR')
  PAT_POLICY = (NETWORK_POLICY_EVALUATION = ENFORCED_NOT_REQUIRED, MAX_EXPIRY_IN_DAYS = 30,
                REQUIRE_ROLE_RESTRICTION_FOR_SERVICE_USERS = FALSE);
-- Without a role restriction the PAT session uses the user's DEFAULT_ROLE; each persona
-- is granted only its own role, so it cannot escalate.
ALTER USER MCP_POC_CEO     SET AUTHENTICATION POLICY AMUSEMENT_PARK_DB.GOVERNANCE.MCP_POC_PAT_POLICY;
ALTER USER MCP_POC_ANALYST SET AUTHENTICATION POLICY AMUSEMENT_PARK_DB.GOVERNANCE.MCP_POC_PAT_POLICY;

-- PATs are generated separately (secret is shown once):
--   ALTER USER MCP_POC_CEO     ADD PROGRAMMATIC ACCESS TOKEN FOUNDRY_CEO     DAYS_TO_EXPIRY = 30;
--   ALTER USER MCP_POC_ANALYST ADD PROGRAMMATIC ACCESS TOKEN FOUNDRY_ANALYST DAYS_TO_EXPIRY = 30;

