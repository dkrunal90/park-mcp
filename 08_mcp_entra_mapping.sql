-- Programmatic Entra ID to Snowflake User/Role Mapping & Key-Pair Credentials

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE COMPUTE_WH;

-- 1. Create mapping table
CREATE TABLE IF NOT EXISTS AMUSEMENT_PARK_DB.GOVERNANCE.ENTRA_USER_MAP (
    ENTRA_USER_ID       VARCHAR(256) PRIMARY KEY, -- e.g. UPN or OID (ceo@amusementpark.com)
    SNOWFLAKE_USER      VARCHAR(256) NOT NULL,    -- e.g. MCP_POC_CEO
    SNOWFLAKE_ROLE      VARCHAR(256) NOT NULL,    -- e.g. PARK_CEO
    DISPLAY_NAME        VARCHAR(256),
    IS_ACTIVE           BOOLEAN DEFAULT TRUE,
    CREATED_AT          TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Seed mapping records
MERGE INTO AMUSEMENT_PARK_DB.GOVERNANCE.ENTRA_USER_MAP t
USING (
    SELECT 'ceo@amusementpark.com' AS ENTRA_USER_ID, 'MCP_POC_CEO' AS SNOWFLAKE_USER, 'PARK_CEO' AS SNOWFLAKE_ROLE, 'CEO Persona' AS DISPLAY_NAME
    UNION ALL
    SELECT 'analyst@amusementpark.com', 'MCP_POC_ANALYST', 'PARK_ANALYST', 'Analyst Persona'
) s
ON t.ENTRA_USER_ID = s.ENTRA_USER_ID
WHEN MATCHED THEN UPDATE SET SNOWFLAKE_USER = s.SNOWFLAKE_USER, SNOWFLAKE_ROLE = s.SNOWFLAKE_ROLE, DISPLAY_NAME = s.DISPLAY_NAME, IS_ACTIVE = TRUE
WHEN NOT MATCHED THEN INSERT (ENTRA_USER_ID, SNOWFLAKE_USER, SNOWFLAKE_ROLE, DISPLAY_NAME) VALUES (s.ENTRA_USER_ID, s.SNOWFLAKE_USER, s.SNOWFLAKE_ROLE, s.DISPLAY_NAME);

-- Grant read access to mapping table for service role
GRANT SELECT ON TABLE AMUSEMENT_PARK_DB.GOVERNANCE.ENTRA_USER_MAP TO ROLE MCP_SERVICE_OWNER;

