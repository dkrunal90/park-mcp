-- 07_mcp_poc_spcs.sql
-- SPCS infrastructure & Service Specification for Entra ID Token Broker MCP

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE COMPUTE_WH;

-- Grant access on secrets and objects to MCP_SERVICE_OWNER
GRANT USAGE ON DATABASE AMUSEMENT_PARK_DB TO ROLE MCP_SERVICE_OWNER;
GRANT USAGE ON SCHEMA AMUSEMENT_PARK_DB.ANALYTICS TO ROLE MCP_SERVICE_OWNER;
GRANT CREATE SERVICE ON SCHEMA AMUSEMENT_PARK_DB.ANALYTICS TO ROLE MCP_SERVICE_OWNER;
GRANT READ ON IMAGE REPOSITORY AMUSEMENT_PARK_DB.ANALYTICS.MCP_REPO TO ROLE MCP_SERVICE_OWNER;
GRANT READ ON SECRET AMUSEMENT_PARK_DB.ANALYTICS.MCP_API_KEY TO ROLE MCP_SERVICE_OWNER;
GRANT READ ON SECRET AMUSEMENT_PARK_DB.ANALYTICS.MCP_KEY_CEO TO ROLE MCP_SERVICE_OWNER;
GRANT READ ON SECRET AMUSEMENT_PARK_DB.ANALYTICS.MCP_KEY_ANALYST TO ROLE MCP_SERVICE_OWNER;
GRANT USAGE ON COMPUTE POOL MCP_POC_POOL TO ROLE MCP_SERVICE_OWNER;
GRANT BIND SERVICE ENDPOINT ON ACCOUNT TO ROLE MCP_SERVICE_OWNER;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE MCP_SERVICE_OWNER;

-- Deploy or Alter Service with Secrets Mounted
USE ROLE MCP_SERVICE_OWNER;

CREATE OR REPLACE SERVICE AMUSEMENT_PARK_DB.ANALYTICS.MCP_POC_SERVICE
  IN COMPUTE POOL MCP_POC_POOL
  FROM SPECIFICATION $$
spec:
  containers:
  - name: mcp
    image: /amusement_park_db/analytics/mcp_repo/park-mcp:latest
    env:
      SERVER_PORT: 8080
      SNOWFLAKE_WAREHOUSE: COMPUTE_WH
      SNOWFLAKE_ACCOUNT: tqmttqp-hw26207
      SNOWFLAKE_HOST: tqmttqp-hw26207.snowflakecomputing.com
    secrets:
    - snowflakeSecret: AMUSEMENT_PARK_DB.ANALYTICS.MCP_API_KEY
      secretKeyRef: secret_string
      envVarName: MCP_API_KEY
    - snowflakeSecret: AMUSEMENT_PARK_DB.ANALYTICS.MCP_KEY_CEO
      secretKeyRef: secret_string
      envVarName: MCP_KEY_CEO
    - snowflakeSecret: AMUSEMENT_PARK_DB.ANALYTICS.MCP_KEY_ANALYST
      secretKeyRef: secret_string
      envVarName: MCP_KEY_ANALYST
    readinessProbe:
      port: 8080
      path: /healthz
  endpoints:
  - name: mcp
    port: 8080
    public: true
capabilities:
  securityContext:
    executeAsCaller: true
serviceRoles:
- name: mcp_user
  endpoints:
  - mcp
$$;

USE ROLE ACCOUNTADMIN;
GRANT SERVICE ROLE AMUSEMENT_PARK_DB.ANALYTICS.MCP_POC_SERVICE!mcp_user TO ROLE PARK_CEO;
GRANT SERVICE ROLE AMUSEMENT_PARK_DB.ANALYTICS.MCP_POC_SERVICE!mcp_user TO ROLE PARK_ANALYST;
